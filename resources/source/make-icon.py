#!/usr/bin/env python3
"""Generate resources/dev.nilltadios.GearLeverCosmic.svg (original artwork):
a red gear with the blue AppImage package box in its hub, on a dark tile.
Run: python3 resources/source/make-icon.py (overwrites the SVG)."""
import math, sys
def cog(cx, cy, r_out, r_in, teeth, tip=0.42, base=0.62, rot=0.0):
    # Teeth with flat tips; tip/base are fractions of the tooth pitch.
    pts = []
    step = 2*math.pi/teeth
    for i in range(teeth):
        a = rot + i*step
        for frac, r in ((-base/2, r_in), (-tip/2, r_out), (tip/2, r_out), (base/2, r_in)):
            t = a + frac*step
            pts.append((cx + r*math.cos(t), cy + r*math.sin(t)))
    return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + "Z"
head = '''<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">
  <!-- Gear Lever COSMIC: a red gear with the blue AppImage package box in its hub. Original artwork, generated by resources/source/make-icon.py. -->
  <defs>
    <linearGradient id="dark" x1="0" y1="0" x2="0" y2="1"><stop stop-color="#2c2c32"/><stop offset="1" stop-color="#0b0b0d"/></linearGradient>
    <linearGradient id="red" x1="0" y1="0" x2="0" y2="1"><stop stop-color="#ff2a2a"/><stop offset="1" stop-color="#c80000"/></linearGradient>
    <radialGradient id="knob" cx=".36" cy=".32" r=".75"><stop stop-color="#ff6a6a"/><stop offset=".45" stop-color="#ff0000"/><stop offset="1" stop-color="#9a0000"/></radialGradient>
  </defs>
  <rect x="6" y="9" width="116" height="114" rx="26" fill="#000" opacity=".3"/>
  <rect x="6" y="6" width="116" height="114" rx="26" fill="url(#dark)"/>
  <rect x="7" y="7" width="114" height="112" rx="25" fill="none" stroke="#fff" stroke-opacity=".09" stroke-width="2"/>
'''
box = lambda x, y, w, h: f'''  <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="3" fill="#3d7bff"/>
  <rect x="{x}" y="{y}" width="{w}" height="{h*0.28:.1f}" rx="3" fill="#2552b8"/>
  <rect x="{x+w/2-w*0.1:.1f}" y="{y}" width="{w*0.2:.1f}" height="{h}" fill="#2552b8"/>
'''
# A: big red cog, blue package in its hub.
a = head + f'  <path d="{cog(64,64,50,40,10)}" fill="#000" opacity=".35" transform="translate(0 2)"/>\n'
a += f'  <path d="{cog(64,63,50,40,10)}" fill="url(#red)"/>\n  <circle cx="64" cy="63" r="27" fill="#141418"/>\n'
a += box(48, 50, 32, 26) + '</svg>\n'
# B: red cog with a lever rising from its hub to a knob, package box under it.
b = head + f'  <path d="{cog(54,72,38,30,9,rot=0.2)}" fill="#000" opacity=".35" transform="translate(0 2)"/>\n'
b += f'  <path d="{cog(54,71,38,30,9,rot=0.2)}" fill="url(#red)"/>\n  <circle cx="54" cy="71" r="19" fill="#141418"/>\n'
b += box(42, 62, 24, 19)
b += '''  <path d="M60 64L90 30" stroke="#000" stroke-opacity=".35" stroke-width="9" stroke-linecap="round"/>
  <path d="M60 62L90 28" stroke="#e8e8ee" stroke-width="7" stroke-linecap="round"/>
  <circle cx="95" cy="26" r="15" fill="#000" opacity=".35"/>
  <circle cx="94" cy="24" r="14" fill="url(#knob)"/>
  <circle cx="89" cy="19" r="4" fill="#fff" opacity=".35"/>
</svg>
'''
import pathlib
out = pathlib.Path(__file__).resolve().parents[1] / "dev.nilltadios.GearLeverCosmic.svg"
out.write_text(a)
print(out)

